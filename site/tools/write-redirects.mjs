// Writes dist/_redirects: the stable /download/* links the site uses.
//
// Every link points at the versioned file of the latest published GitHub release, so the
// downloaded file always has the version in its name (cashflow-0.1.2-windows-x64-setup.exe).
// The version is read from the GitHub API at build time. The release workflow triggers a new
// site build once a release is published, which is when a new version reaches the site.
//
// If the API cannot be reached, the links fall back to the releases page so they never break.

import { writeFileSync } from 'node:fs';

const REPO = 'isaul32/cashflow';
const API = `https://api.github.com/repos/${REPO}/releases/latest`;

// Link name -> file name pattern, {v} is the version.
const FILES = {
  'windows-installer': 'cashflow-{v}-windows-x64-setup.exe',
  'windows-portable': 'cashflow-{v}-windows-x64-portable.zip',
  macos: 'cashflow-{v}-macos-arm64.dmg',
  'linux-appimage-x64': 'cashflow-{v}-linux-x64.AppImage',
  'linux-appimage-arm64': 'cashflow-{v}-linux-arm64.AppImage',
  'linux-deb-x64': 'cashflow-{v}-linux-x64.deb',
  'linux-deb-arm64': 'cashflow-{v}-linux-arm64.deb',
};

async function latestTag() {
  const headers = { Accept: 'application/vnd.github+json', 'User-Agent': 'cashflow-site-build' };
  // Optional: a token lifts the anonymous rate limit on shared build machines.
  if (process.env.GITHUB_TOKEN) headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;
  const res = await fetch(API, { headers });
  if (!res.ok) throw new Error(`GitHub API answered ${res.status}`);
  const { tag_name } = await res.json();
  if (!/^v\d+\.\d+\.\d+$/.test(tag_name)) throw new Error(`unexpected tag "${tag_name}"`);
  return tag_name;
}

let tag = null;
try {
  tag = await latestTag();
  console.log(`Download links point at release ${tag}`);
} catch (e) {
  console.warn(`Could not read the latest release (${e.message}); linking to the releases page.`);
}

const lines = [
  '# Generated by tools/write-redirects.mjs at build time. Do not edit.',
  '',
];
for (const [name, pattern] of Object.entries(FILES)) {
  const target = tag
    ? `https://github.com/${REPO}/releases/download/${tag}/${pattern.replace('{v}', tag.slice(1))}`
    : `https://github.com/${REPO}/releases/latest`;
  lines.push(`/download/${name} ${target} 302`);
}
writeFileSync(new URL('../dist/_redirects', import.meta.url), lines.join('\n') + '\n');
